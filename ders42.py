import math
print(math.sqrt(36))#karekök alma
print(math.pow(6,2))#üsk 36 üst 2 kuvveti
print(math.ceil(10.45)) #yukarı yuvarlama 11 olarak yuvarlıyor
print(math.floor(9.45)) #tabana yuvarlama
print(math.factorial(5))#faktoriyel 5
print(math.fabs(-10))#mutlaka değer
print(math.gcd(12,18))#en büyük ortak böleni buluyor
print(math.lcm(12,18))#en küçük ortak katları bulur
print(math.log10(100))
print(math.trunc(10.5))#ondalık kısmını atar
